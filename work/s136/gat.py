k=.074
kx,ky=.08,.085
def M(p):
  x,y=p
  X=45+(x-276)*kx
  if x>458:X=59.56+(x-458)/(540-458)*.44
  return (X,83.6+(y-564)*ky)
def path(P):
  P=[M(p) for p in P];n=len(P);d=f'M{P[0][0]:.2f} {P[0][1]:.2f}'
  for i in range(n):
    p0=P[i-1];p1=P[i];p2=P[(i+1)%n];p3=P[(i+2)%n]
    c1=(p1[0]+(p2[0]-p0[0])/6,p1[1]+(p2[1]-p0[1])/6);c2=(p2[0]-(p3[0]-p1[0])/6,p2[1]-(p3[1]-p1[1])/6)
    d+=f' C{c1[0]:.2f} {c1[1]:.2f} {c2[0]:.2f} {c2[1]:.2f} {p2[0]:.2f} {p2[1]:.2f}'
  return d+'Z'
