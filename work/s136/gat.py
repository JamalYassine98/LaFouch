import json
OUT=[(44,366),(120,368),(220,378),(320,396),(400,418),(455,440),(500,458),(540,462),(540,522),(505,528),(488,548),(475,595),(452,642),(415,684),(360,710),(290,721),(225,714),(170,692),(130,648),(100,585),(72,505),(52,430),(45,388)]
